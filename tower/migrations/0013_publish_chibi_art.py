def publish_chibi(apps, schema_editor):
    alias = schema_editor.connection.alias
    def rows(name):
        return apps.get_model("tower", name).objects.using(alias)
    for snapshot in CHIBI_SETS:
        defaults = {key: value for key, value in snapshot.items() if key != "slug"}
        version, created = rows("CharacterSetVersion").get_or_create(slug=snapshot["slug"], defaults=defaults)
        if any(getattr(version, key) != value for key, value in defaults.items()):
            raise RuntimeError("Published character-set revisions are immutable.")
        publication, new = rows("CharacterSetPublication").get_or_create(
            hero_id=snapshot["hero_id"], defaults={"version_id": version.pk})
        before = publication.version.slug
        if publication.version.revision > version.revision:
            continue
        if publication.version_id != version.pk:
            publication.version_id = version.pk
            publication.save(using=alias, update_fields=["version"])
        for component in snapshot["config"]["components"].values():
            item, new_item = rows("CosmeticDefinition").get_or_create(slug=component["id"], defaults={
                "slot": component["slot"], "labels": component["labels"], "price": 0,
                "acquisition": "character_set", "set_version_id": version.pk, "appearance": component})
            if item.acquisition != "character_set" or item.slot != component["slot"] or item.set_version.hero_id != snapshot["hero_id"]:
                raise RuntimeError("A character set cannot replace another cosmetic.")
            if item.set_version_id != version.pk:
                item.set_version_id, item.labels, item.appearance = version.pk, component["labels"], component
                item.save(using=alias, update_fields=["set_version", "labels", "appearance"])
        if created or new or before != version.slug:
            rows("TowerAuditEvent").create(event_type="character_set_publish", metadata={
                "hero": snapshot["hero_id"], "before": None if new else before,
                "after": version.slug, "placeholder": False, "source": "migration_0013"})


